@pytest.mark.parametrize("protocol", list(range(pickle.HIGHEST_PROTOCOL + 1)))
def test_new_pickles_reference_only_historical_globals(protocol):
    for obj in _new_instances():
        data = pickle.dumps(obj, protocol=protocol)
        refs = _referenced_globals(data)
        assert refs, "expected at least one class global in the pickle"
        for ref in refs:
            assert ref in HISTORICAL_DTO_GLOBALS | STDLIB_PICKLE_GLOBALS, (
                f"protocol {protocol} pickle of {type(obj).__qualname__} references "
                f"{ref}, which does not exist at the prior release head"
            )


@pytest.mark.parametrize("protocol", list(range(pickle.HIGHEST_PROTOCOL + 1)))
def test_new_pickles_roundtrip_under_historical_identity(protocol):
    for obj in _new_instances():
        clone = pickle.loads(pickle.dumps(obj, protocol=protocol))
        assert type(clone) is type(obj)
        assert type(clone).__module__ == type(obj).__module__
        assert type(clone).__qualname__ == type(obj).__qualname__
        assert not type(clone).__qualname__.startswith("_")
        assert clone == obj
