"""Bidirectional pickle rollback-compatibility probes for domain-local DTOs.

Five domain-local trace/recommendation DTO classes keep a stable historical
runtime identity (module path + class name). Two invariants protect rollback
between this tree and the prior public release head
``e080170ba76b9164d2757b9afc3d6b27f3af4850``:

* base -> new: pickles produced at the prior release load on this tree.
  The fixtures under ``tests/fixtures/pickle_compat/`` were generated by
  executing the prior release's module sources (all stdlib-only) in an
  isolated interpreter and pickling representative instances at protocol 2.
  The ``proxy_server_stage_trace.pkl`` fixture covers the prior release's
  field-identical ``tokenpak.proxy.server.StageTrace`` definition; it was
  derived from the tracing fixture by rewriting the module string inside the
  protocol-2 GLOBAL opcode and is opcode-verified below before use.

* new -> base: pickles produced by this tree reference only global names
  that exist at the prior release, so the prior code can still load them
  after a rollback.
"""

from __future__ import annotations

import pickle
import pickletools
