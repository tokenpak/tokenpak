FIXTURE_DIR = Path(__file__).parent / "fixtures" / "pickle_compat"

# Every class global that pickles of these DTOs may reference. Each pair
# resolves at the prior public release head as well as on this tree.
HISTORICAL_DTO_GLOBALS = {
    ("tokenpak.services.optimization.trace", "StageTrace"),
    ("tokenpak.services.optimization.trace", "OptimizationTrace"),
    ("tokenpak.proxy.tracing", "StageTrace"),
    ("tokenpak.proxy.server", "StageTrace"),
    ("tokenpak.telemetry.pipeline_trace", "StageTrace"),
    ("tokenpak.telemetry.recommendations", "Recommendation"),
}

# Plumbing globals the stdlib pickler may emit for plain-object reduction
# at old protocols. All exist unchanged at the prior release (stdlib).
STDLIB_PICKLE_GLOBALS = {
    ("copy_reg", "_reconstructor"),
    ("copyreg", "_reconstructor"),
    ("__builtin__", "object"),
    ("builtins", "object"),
}


def _referenced_globals(data: bytes) -> list[tuple[str, str]]:
    """Return every (module, name) global reference inside a pickle.

    GLOBAL carries module/name inline. STACK_GLOBAL consumes the two most
    recently pushed strings, which may be fresh string pushes or memo
    retrievals (the pickler memoizes module strings and reuses them via
    *GET for later classes from the same module), so string pushes and the
    memo are both tracked.
    """
    refs: list[tuple[str, str]] = []
    pushed: list[str] = []  # string values pushed onto the stack, in order
    memo: dict[object, str] = {}
    memoize_count = 0
    pending_string = None  # last op pushed this string (still top of stack)
    for op, arg, _pos in pickletools.genops(data):
        name = op.name
        if name in ("SHORT_BINUNICODE", "BINUNICODE", "BINUNICODE8", "UNICODE"):
            pushed.append(arg)
            pending_string = arg
            continue
        if name == "MEMOIZE":
            # Implicit memo: sequential index, memoizes top of stack.
            if pending_string is not None:
                memo[memoize_count] = pending_string
            memoize_count += 1
            continue  # MEMOIZE does not pop; the string stays on top
        if name in ("PUT", "BINPUT", "LONG_BINPUT"):
            if pending_string is not None:
                memo[arg] = pending_string
            continue  # PUT does not pop either
        if name in ("GET", "BINGET", "LONG_BINGET"):
            if arg in memo:
                pushed.append(memo[arg])
                pending_string = memo[arg]
                continue
        elif name == "GLOBAL":
            module, gname = arg.split(" ")
            refs.append((module, gname))
        elif name == "STACK_GLOBAL":
            refs.append((pushed[-2], pushed[-1]))
        pending_string = None
    return refs


def _new_instances():
    svc_stage = service_trace.StageTrace(
        name="cache", eligible=True, skip_reason="", applied=False, duration_ms=0.5, detail="probe"
    )
    svc_trace = service_trace.OptimizationTrace(
        request_id="probe-1", mode="observe", started_at=1234.5, body_bytes_in=10, body_bytes_out=10
    )
    svc_trace.add_stage(svc_stage)
    return [
        svc_stage,
        svc_trace,
        proxy_tracing.StageTrace(
            name="compress",
            enabled=True,
            input_tokens=100,
            output_tokens=80,
            tokens_delta=-20,
            duration_ms=5.0,
            details={"src": "probe"},
        ),
        telemetry_trace.StageTrace(
            name="capsule",
            enabled=True,
            input_tokens=10,
            output_tokens=7,
            tokens_delta=-3,
            details={"src": "probe"},
            duration_ms=1.25,
        ),
        telemetry_rec.Recommendation(
            id="cache.lookup",
            severity="high",
            title="Enable cache lookups",
            evidence={"lookups": 0},
            action="Enable the cache.",
            expected="Lookups become nonzero.",
        ),
    ]


