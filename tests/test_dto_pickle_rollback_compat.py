@pytest.mark.parametrize("fixture_name", sorted(BASE_FIXTURES))
def test_base_release_pickle_loads_on_current_tree(fixture_name):
    expected_cls, expected_fields = BASE_FIXTURES[fixture_name]
    data = (FIXTURE_DIR / fixture_name).read_bytes()

    # Fixture integrity: it must reference only historical DTO or stdlib
    # globals — i.e. it is genuinely shaped like a prior-release pickle.
    for ref in _referenced_globals(data):
        assert ref in HISTORICAL_DTO_GLOBALS | STDLIB_PICKLE_GLOBALS, ref

    obj = pickle.loads(data)
    assert type(obj) is expected_cls
    for field_name, expected_value in expected_fields.items():
        assert getattr(obj, field_name) == expected_value


def test_server_module_still_exposes_stage_trace_global():
    # The prior release pickled proxy stage traces under
    # tokenpak.proxy.server.StageTrace as well; that global must keep
    # resolving so those pickles remain loadable.
    from tokenpak.proxy import server

    assert server.StageTrace is proxy_tracing.StageTrace


